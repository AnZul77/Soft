from typing import Optional, List
from pydantic import BaseModel, Field

class CitationItem(BaseModel):
    article_id: str
    title: str
    source: str
    url: str
    snippet: str
    similarity_score: Optional[float] = None

class SupplyChainLink(BaseModel):
    source_ticker: str
    target_ticker: str
    relationship_type: str # 'SUPPLIER', 'CUSTOMER', 'COMPETITOR', 'SUBSIDIARY'
    description: Optional[str] = None
    confidence_score: float = 1.0

class ExplainImpactRequest(BaseModel):
    portfolio_id: str
    ticker: str
    event_description: Optional[str] = None
    price_change_pct: Optional[float] = None

class ExplainImpactResponse(BaseModel):
    ticker: str
    summary_headline: str
    portfolio_exposure_pct: float
    portfolio_holding_shares: float
    portfolio_holding_value: float
    direct_holdings_affected: List[str]
    supply_chain_links: List[SupplyChainLink]
    evidence_citations: List[CitationItem]
    sentiment_impact: str # 'BEARISH', 'BULLISH', 'NEUTRAL', 'MIXED'
    analysis_text: str
    abstention: bool = False
    regulatory_disclaimer: str = (
        "DISCLAIMER: This analysis is generated by an artificial intelligence decision-support model "
        "for educational and informational purposes only. It does not constitute financial, investment, "
        "or legal advice. Past performance and algorithmic inferences are not indicative of future results."
    )

class AIResearchQuery(BaseModel):
    query: str = Field(..., min_length=2, max_length=500)
    ticker: Optional[str] = None
    limit: int = Field(default=5, ge=1, le=20)

class AIResearchResponse(BaseModel):
    query: str
    ticker: Optional[str] = None
    answer: str
    citations: List[CitationItem]
    abstention: bool = False
    disclaimer: str = (
        "DISCLAIMER: Educational decision-support only. Not financial or investment advice."
    )
